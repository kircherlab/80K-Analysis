#' Load preprocessed GTEx eQTLs at the exact variant position.
#' Only arcs whose variant anchor matches pos are returned.
#' v_start in the file is already 0-based; pos argument is also 0-based.
load_gtex <- function(chrom, pos) {
  if (!file.exists(GTEX_PROC)) {
    message("GTEx preprocessed file not found. Run: python src/preprocess_eqtl_data.py")
    return(NULL)
  }
  tryCatch({
    dt <- fread(
      cmd = sprintf(
        "zcat '%s' | awk -v c='%s' -v p=%d 'NR==1 || ($1==c && $2==p)'",
        GTEX_PROC, chrom, pos
      ),
      sep = "\t"
    )
    if (nrow(dt) == 0L) return(NULL)
    # is_brain comes from Python as "True"/"False" strings
    dt[, is_brain := is_brain %in% c("True", "TRUE", TRUE)]
    dt
  }, error = function(e) { message("GTEx load error: ", e$message); NULL })
}

#' Load preprocessed Metabrain eQTLs at the exact variant position.
#' metabrain_dedup: "all_sig" (default), "cortex_EUR", or "best_pvalue"
load_metabrain <- function(chrom, pos, metabrain_dedup = "all_sig") {
  if (!file.exists(META_PROC)) {
    message("Metabrain preprocessed file not found. Run: python src/preprocess_eqtl_data.py")
    return(NULL)
  }
  tryCatch({
    dt <- fread(
      cmd = sprintf(
        "zcat '%s' | awk -v c='%s' -v p=%d 'NR==1 || ($1==c && $13==p)'",
        META_PROC, chrom, pos
      ),
      sep = "\t"
    )
    if (nrow(dt) == 0L) return(NULL)

    # Convert Python "True"/"False" strings to R logical
    as_lgl <- function(x) x %in% c("True", "TRUE", TRUE)
    dt[, is_sig         := as_lgl(is_sig)]
    dt[, is_cortex_EUR  := as_lgl(is_cortex_EUR)]
    dt[, is_best_pvalue := as_lgl(is_best_pvalue)]

    # Apply dedup mode filter
    if (metabrain_dedup == "cortex_EUR") {
      dt <- dt[is_cortex_EUR == TRUE]
    } else if (metabrain_dedup == "best_pvalue") {
      dt <- dt[is_best_pvalue == TRUE]
    }
    # "all_sig": no tissue filter — keep all rows; significance filtered downstream
    if (nrow(dt) == 0L) return(NULL)
    dt
  }, error = function(e) { message("Metabrain load error: ", e$message); NULL })
}

