}

#' Build one InteractionTrack for a single (color, lwd) group.
make_interaction_track <- function(sub_df, col, lwd_val, name, chrom, genome) {
  if (nrow(sub_df) == 0L) return(NULL)
  gi <- GenomicInteractions(
    GRanges(sub_df[["v_chr"]], IRanges(as.integer(sub_df[["v_start"]]) + 1L,
                                       as.integer(sub_df[["v_end"]]))),
    GRanges(sub_df[["g_chr"]], IRanges(as.integer(sub_df[["g_start"]]) + 1L,
                                       as.integer(sub_df[["g_end"]])))
  )
  if (length(gi) == 0L) return(NULL)
  tr <- InteractionTrack(gi, name = name, chromosome = chrom)
  displayPars(tr) <- list(
    col.interactions      = col,
    col.outside           = col,
    col.anchors.fill      = "white",
    col.anchors.line      = "white",
    interaction.dimension = "height",
    anchor.height         = 0,
    lwd.interactions      = lwd_val,
    showFeatureId         = FALSE,
    showAnchors           = FALSE,
    background.title      = "white",
    col.title             = "black"
  )
  tr
}

#' Build eQTL arc tracks from a pre-filtered data frame.
#'
#' df must have columns: v_chr, v_start, v_end, g_chr, g_start, g_end,
#'                        beta, p_val, is_sig, is_brain
#'
#' arc_mode:
#'   "split_panel" — returns named list: $positive (tracks), $negative (tracks)
#'   "color_only"  — returns list of all tracks (positive = blue, negative = warm)
build_eqtl_arc_tracks <- function(df, name, genome, chrom,
                                   arc_mode   = "split_panel",
                                   n_bins     = 5L,
                                   arc_lwd    = 2.5) {
  if (is.null(df) || nrow(df) == 0L) return(list())

  df <- as.data.frame(df)

  # Keep only significant arcs
  df <- df[df$is_sig, , drop = FALSE]
  if (nrow(df) == 0L) return(list())

  df$abs_beta <- abs(df$beta)
  df$is_pos   <- df$beta >= 0

  # 2-class color: brain = blue, non-brain = gray
  df$color   <- ifelse(df$is_brain, COL_BRAIN_DARK, "#888888")
  df$lwd_val <- arc_lwd

  # One track per color class (2 tracks max per source)
  df$track_key <- df$color

  build_group <- function(sub, label) {
    Filter(Negate(is.null), lapply(unique(sub$track_key), function(k) {
      rows <- sub[sub$track_key == k, , drop = FALSE]
      make_interaction_track(rows, rows$color[1L], rows$lwd_val[1L],
                             label, chrom, genome)
    }))
  }

  if (arc_mode == "split_panel") {
    pos_df <- df[df$is_pos, , drop = FALSE]
    neg_df <- df[!df$is_pos, , drop = FALSE]
    list(
      positive = build_group(pos_df, paste0(name, "\n(+beta)")),
      negative = build_group(neg_df, paste0(name, "\n(-beta)"))
    )
  } else {
    # color_only: one flat list of tracks
    build_group(df, name)
  }
}

build_ems_track <- function(dt, genome, chrom) {
  dt[, is_sig := rf_score_raw > 0.5]
  dt[, color  := mapply(beta_to_color, 0.5, is_brain, is_sig)]  # fixed beta for EMS

  max_score <- max(dt$ems_normalized, na.rm = TRUE)
  ylim_val  <- c(0, max_score * 1.05)

  groups    <- split(dt, dt$color)
  subtracks <- lapply(names(groups), function(col) {
    g  <- groups[[col]]
    g  <- g[, .(ems_normalized = max(ems_normalized, na.rm = TRUE)), by = pos0]
    gr <- GRanges(chrom, IRanges(g$pos0, g$pos0 + 1L))
    DataTrack(range = gr, data = g$ems_normalized,
              type = "h", genome = genome, name = "EMS",
              col = col, col.histogram = col, fill.histogram = col,
              ylim = ylim_val, background.title = "white", col.title = "black")
  })

  if (length(subtracks) == 1L) return(subtracks[[1L]])
  OverlayTrack(trackList = subtracks, name = "EMS")
}

build_gene_track <- function(chrom, from, to, genome) {
  chrom_num <- sub("^chr", "", chrom)
  mirrors   <- c("https://www.ensembl.org", "https://useast.ensembl.org",
                 "https://asia.ensembl.org")

  for (host in mirrors) {
    track <- tryCatch({
      ensembl <- biomaRt::useMart(
        "ENSEMBL_MART_ENSEMBL", dataset = "hsapiens_gene_ensembl",
        host = host
      )
      # transcript_is_canonical is reliable as an attribute but not as a BioMart filter;
      # fetch IDs first, filter in R, then pass as ensembl_transcript_id filter.
      canon_tbl <- biomaRt::getBM(
        attributes = c("ensembl_transcript_id", "transcript_is_canonical"),
        filters    = "chromosomal_region",
        values     = list(paste0(chrom_num, ":", from, ":", to)),
        mart       = ensembl
      )
      canon_ids <- canon_tbl$ensembl_transcript_id[
        !is.na(canon_tbl$transcript_is_canonical) & canon_tbl$transcript_is_canonical == 1
      ]
      tr_filter <- if (length(canon_ids) > 0L)
        list(ensembl_transcript_id = canon_ids) else list()

      BiomartGeneRegionTrack(
        genome               = genome,
        chromosome           = chrom,
        start                = from,
        end                  = to,
        name                 = "Genes",
        biomart              = ensembl,
        transcriptAnnotation = "symbol",
        filter               = tr_filter,
        col.line             = "#444444",
        fill                 = "#444444",
        col                  = "#444444",
        background.title     = "white",
        col.title            = "black"
      )
    }, error = function(e) {
      message("  Gene track mirror failed (", host, "): ", e$message); NULL
    })
    if (!is.null(track)) return(track)
  }

  message("Gene track unavailable (BioMart): all mirrors failed.")
  NULL
}

# ── rsID resolver ──────────────────────────────────────────────────────────────

# Try Ensembl REST API — separate infrastructure from BioMart, usually more reliable.
.resolve_via_ensembl_rest <- function(rsid) {
  url <- paste0("https://rest.ensembl.org/variation/human/",
                rsid, "?content-type=application/json")
  tryCatch({
    resp <- httr::GET(url, httr::timeout(15))
    if (httr::status_code(resp) != 200L) return(NULL)
    data <- httr::content(resp, as = "parsed")
    for (m in data$mappings) {
      if (!identical(m$assembly_name, "GRCh38")) next
      # location format: "15:67064084-67064084"
      parts      <- strsplit(m$location, "[:-]")[[1L]]
      chrom      <- paste0("chr", parts[1L])
      pos_0based <- as.integer(parts[2L]) - 1L
      alleles    <- strsplit(m$allele_string, "/")[[1L]]
      if (length(alleles) < 2L) next
      return(list(chrom = chrom, pos = pos_0based,
                  ref = alleles[1L], alt = alleles[2L]))
    }
    NULL
  }, error = function(e) NULL)
}

resolve_rsid <- function(rsid) {
  message("  Resolving ", rsid, " ...")

  # Try 1: Ensembl REST API (no SOAP overhead, different backend)
  message("    Trying Ensembl REST API...")
  coords <- .resolve_via_ensembl_rest(rsid)
  if (!is.null(coords)) {
    message("  Resolved via REST: ", coords$chrom, ":", coords$pos,
            " (0-based) | alleles: ", coords$ref, ">", coords$alt)
    return(coords)
  }

  # Try 2: BioMart SOAP mirrors
  message("    REST failed — trying BioMart mirrors...")
  mirrors <- c("https://www.ensembl.org", "https://useast.ensembl.org",
               "https://asia.ensembl.org")
  for (host in mirrors) {
    mart <- tryCatch(
      biomaRt::useMart("ENSEMBL_MART_SNP", dataset = "hsapiens_snp", host = host),
      error = function(e) NULL
    )
    if (is.null(mart)) next
    res <- tryCatch(
      biomaRt::getBM(
        attributes = c("refsnp_id", "chr_name", "chrom_start", "allele"),
        filters    = "snp_filter",
        values     = rsid,
        mart       = mart
      ),
      error = function(e) NULL
    )
    if (is.null(res) || nrow(res) == 0L) next
    row        <- res[1L, ]
    chrom      <- paste0("chr", row$chr_name)
    pos_0based <- as.integer(row$chrom_start) - 1L
    alleles    <- strsplit(as.character(row$allele), "/")[[1L]]
    ref        <- alleles[1L]
    alt        <- if (length(alleles) > 1L) alleles[2L] else NA_character_
    message("  Resolved via BioMart (", host, "): ", chrom, ":", pos_0based,
            " (0-based) | alleles: ", ref, ">", alt)
    return(list(chrom = chrom, pos = pos_0based, ref = ref, alt = alt))
  }

  stop("Could not resolve ", rsid, " via Ensembl REST or BioMart. ",
       "Pass chrom/pos/ref/alt directly instead.")
}

# ── UCSC / external bigwig ATAC track builder ─────────────────────────────────
#' Build Gviz DataTracks from bigwig sources, hub URLs, or catalog ids.
#' Requires ucsc_atac_explorer.R to be sourced (auto-sourced if not yet loaded).
#'
#' @param ucsc_atac  Character vector of any mix of:
#'   - UCSC browser URLs containing hubUrl= (all bigwigs in that hub for the region)
#'   - Track hub .txt URLs (e.g. "https://ggoma.s3.amazonaws.com/hub_basic.txt")
#'   - Direct bigwig URLs (https://, file://, or absolute path ending in .bw/.bigwig)
#'   - Catalog ids from ATAC_HUB_CATALOG$id (e.g. "boca_glut_dlPFC")
#'   Named elements use the name as the track label (only applies to single-track entries).
build_ucsc_atac_tracks <- function(ucsc_atac, chrom, from, to) {
  .ensure_explorer <- function() {
    if (!exists("build_bw_track", mode = "function")) {
      explorer <- file.path("src", "ucsc_atac_explorer.R")
      if (file.exists(explorer)) source(explorer)
      else message("[WARN] ucsc_atac_explorer.R not found — source it manually")
    }
  }

  tracks_out <- list()
  for (i in seq_along(ucsc_atac)) {
    entry <- ucsc_atac[[i]]
    label <- if (!is.null(names(ucsc_atac)) && nchar(names(ucsc_atac)[i]) > 0)
               names(ucsc_atac)[i] else NULL

    .ensure_explorer()

    # Detect entry type and collect one or more DataTrack objects
    new_tracks <- if (grepl("hubUrl=", entry, fixed = TRUE)) {
      # Full UCSC browser URL — extract just the hub URL, use caller's region
      parsed <- if (exists("parse_ucsc_url", mode = "function")) parse_ucsc_url(entry) else NULL
      if (!is.null(parsed) && !is.null(parsed$hub_url) &&
          exists("build_hub_tracks", mode = "function")) {
        build_hub_tracks(parsed$hub_url, chrom, from, to,
                         genome = parsed$genome %||% "hg38")
      } else { message("[WARN] Cannot resolve hub from UCSC URL: ", entry); NULL }

    } else if (grepl("\\.txt(\\?.*)?$", entry, ignore.case = TRUE)) {
      # Direct hub.txt URL — load all bigwig tracks for the region
      if (exists("build_hub_tracks", mode = "function"))
        build_hub_tracks(entry, chrom, from, to)
      else { message("[WARN] build_hub_tracks not available"); NULL }

    } else if (grepl("^https?://|^file://|^/", entry)) {
      # Direct bigwig URL
      tr <- build_bw_track(entry, chrom, from, to,
                           name = label %||% basename(entry))
      list(tr)

    } else {
      # Catalog ID
      if (exists("build_catalog_track", mode = "function")) {
        tr <- build_catalog_track(entry, chrom, from, to)
        if (!is.null(tr) && !is.null(label))
          Gviz::displayPars(tr) <- list(name = label)
        list(tr)
      } else { message("[WARN] build_catalog_track not available"); NULL }
    }

    for (tr in Filter(Negate(is.null), new_tracks %||% list()))
      tracks_out[[length(tracks_out) + 1L]] <- tr
  }
  tracks_out
}

# ── Main plotting function ──────────────────────────────────────────────────────
#' Genome-browser plot for a single MPRA variant.
#'
#' @param chrom          UCSC chromosome, e.g. "chr5"
#' @param pos            0-based position
#' @param ref            Reference allele
#' @param alt            Alternate allele
#' @param rsid           dbSNP rsID — resolves chrom/pos/ref/alt via BioMart
#' @param window         Half-window in bp (default 200 kb)
#' @param outfile        Output PDF path; auto-generated if NULL
#' @param metabrain_dedup  "all_sig" (default), "cortex_EUR", or "best_pvalue"
#'   all_sig:     show all significant eQTLs across all tissues — one arc per gene×tissue
#'   cortex_EUR:  show only cortex_EUR tissue rows — one arc per gene
#'   best_pvalue: show one arc per gene from the most significant tissue
#' @param arc_mode         "split_panel" (default) or "color_only"
#'   split_panel: positive-beta arcs in upper sub-track, negative in lower sub-track
#'   color_only:  all arcs in one track; positive = blue, negative = warm orange
#' @param ucsc_atac      Character vector of ATAC-seq bigwig tracks to add.
#'   Each element is a catalog id (see browse_catalog()) or a direct bigwig URL.
#'   Example: c("boca_glut_dlPFC", "boca_glut_ACC")
#'   Requires source("src/ucsc_atac_explorer.R") for catalog id resolution.
#' @param col_region_sig  Color for MPRA regions with active sequence
#' @param col_var_up      Color for significant activating variants
#' @param col_var_down    Color for significant repressive variants
plot_variant <- function(chrom = NULL, pos = NULL, ref = NULL, alt = NULL,
                          rsid   = NULL,
                          window = 200000L,
                          outfile = NULL,
                          metabrain_dedup = "all_sig",
                          arc_mode        = "split_panel",
                          brain_atac      = NULL,
                          ucsc_atac       = NULL,
                          show_ccres      = TRUE,
                          show_ngn2_atac  = TRUE,
                          show_gtex       = TRUE,
                          show_ems        = TRUE,
                          arc_lwd         = 2.5,
                          col_region_sig  = COL_REGION_SIG,
                          col_var_up      = COL_VAR_SIG_UP,
                          col_var_down    = COL_VAR_SIG_DOWN) {

  if (!is.null(rsid)) {
    coords <- resolve_rsid(rsid)
    chrom  <- coords$chrom; pos <- coords$pos
    ref    <- coords$ref;   alt <- coords$alt
  } else if (is.null(chrom) || is.null(pos) || is.null(ref) || is.null(alt)) {
    stop("Provide either rsid or all of: chrom, pos, ref, alt")
  }

  stopifnot(metabrain_dedup %in% c("all_sig", "cortex_EUR", "best_pvalue"))
  stopifnot(arc_mode %in% c("split_panel", "color_only"))

  genome <- "hg38"
  from   <- pos - window
  to     <- pos + window

  if (is.null(outfile)) {
    name_base <- if (!is.null(rsid)) rsid else sprintf("%s_%d_%s_%s", chrom, pos, ref, alt)
    outfile   <- file.path(OUTPUT_DIR, sprintf("%s_%s_%s.pdf", name_base, metabrain_dedup, arc_mode))
  }
  dir.create(dirname(outfile), showWarnings = FALSE, recursive = TRUE)

  message(sprintf("\nPlotting %s:%d %s>%s  [%d, %d]", chrom, pos, ref, alt, from, to))
  message(sprintf("  metabrain_dedup=%s  arc_mode=%s", metabrain_dedup, arc_mode))

  # ── Load all data ─────────────────────────────────────────────────────────────
  message("  Loading data...")
  mpra_dt     <- load_mpra(chrom, from, to)
  regions_dt  <- load_mpra_regions(chrom, from, to)
  gtex_df     <- if (show_gtex) load_gtex(chrom, pos) else NULL
  meta_df     <- load_metabrain(chrom, pos, metabrain_dedup)
  ems_dt      <- if (show_ems) load_ems(chrom, from, to) else NULL
  ems_arcs_df <- if (show_ems) load_ems_arcs(chrom, pos) else NULL

  # Report MetaBrain eQTL gene targets with p-value and beta (significant rows only)
  meta_genes_df <- if (!is.null(meta_df) && nrow(meta_df) > 0L) {
    d <- as.data.frame(meta_df)
    d <- d[d$is_sig, c("gene_name", "Tissue", "p_val", "beta")]
    d[order(d$gene_name, d$p_val), ]
  } else {
    data.frame(gene_name = character(0), Tissue = character(0),
               p_val = numeric(0), beta = numeric(0))
  }
  if (nrow(meta_genes_df) > 0L) {
    message("  MetaBrain eQTL genes:")
    for (i in seq_len(nrow(meta_genes_df))) {
      r <- meta_genes_df[i, ]
      message(sprintf("    %-12s tissue=%-14s p=%.3g  beta=%.3f",
                      r$gene_name, r$Tissue, r$p_val, r$beta))
    }
  }
  atac_dt    <- load_atac(chrom, from, to)
  ccre_dt    <- if (show_ccres) load_screen_ccres(chrom, from, to) else NULL
  # Local brain ATAC bigwig tracks (GSE113480; built only when brain_atac is set)
  brain_atac_trs <- if (!is.null(brain_atac) && length(brain_atac) > 0L)
    build_brain_atac_tracks(chrom, from, to, which = brain_atac)
  else list()
  # UCSC / external bigwig ATAC tracks (fetched on demand; NULL if ucsc_atac not set)
  ucsc_atac_trs <- if (!is.null(ucsc_atac))
    build_ucsc_atac_tracks(ucsc_atac, chrom, from + 1L, to)
  else list()
  message("  Loading gene models...")
  gene_tr    <- build_gene_track(chrom, from, to, genome)

  # ── Diagnostic summary ────────────────────────────────────────────────────────
  message(sprintf(
    "  MPRA=%s (%s sig) | regions=%s | GTEx=%s (%s sig, %s brain) | Meta=%s (%s sig) | EMS=%s | EMS arcs=%s (%s sig) | ATAC=%s peaks | brain_bw=%s | UCSC_ATAC=%s tracks | gene=%s",
    if (is.null(mpra_dt)) "0" else nrow(mpra_dt),
    if (is.null(mpra_dt)) "0" else sum(mpra_dt$is_sig),
    if (is.null(regions_dt)) "0" else nrow(regions_dt),
    if (is.null(gtex_df)) "0" else nrow(gtex_df),
    if (is.null(gtex_df)) "0" else sum(gtex_df$pip > 0.1, na.rm = TRUE),
    if (is.null(gtex_df)) "0" else sum(gtex_df$is_brain, na.rm = TRUE),
    if (is.null(meta_df)) "0" else nrow(meta_df),
    if (is.null(meta_df)) "0" else sum(meta_df$is_sig, na.rm = TRUE),
    if (is.null(ems_dt))  "0" else nrow(ems_dt),
    if (is.null(ems_arcs_df)) "0" else nrow(ems_arcs_df),
    if (is.null(ems_arcs_df)) "0" else sum(ems_arcs_df$is_sig, na.rm = TRUE),
    if (is.null(atac_dt)) "0" else nrow(atac_dt),
    length(brain_atac_trs),
    length(ucsc_atac_trs),
    if (is.null(gene_tr)) "missing" else "OK"
  ))

  # ── Build tracks (top → bottom) ───────────────────────────────────────────────
  tracks      <- list()
  track_sizes <- numeric(0)

  safe <- function(label, expr) {
    tryCatch(expr, error = function(e) {
      message("  [TRACK FAILED: ", label, "]: ", e$message); NULL
    })
  }

  push <- function(tr_or_list, size = 1) {
    items <- if (is.list(tr_or_list) && !inherits(tr_or_list, "GdObject"))
               tr_or_list else list(tr_or_list)
    for (t in items) {
      if (is.null(t)) next
      tracks[[length(tracks) + 1L]]        <<- t
      track_sizes[length(track_sizes) + 1L] <<- size
    }
  }

  # 1. Genome axis
  push(safe("Axis", GenomeAxisTrack(col = "black")), size = 0.25)

  # 2. Gene models
  if (!is.null(gene_tr)) push(gene_tr, size = 2.0)

  # 3. MPRA tested regions
  if (!is.null(regions_dt))
    push(safe("MPRA Regions",
              build_mpra_region_track(regions_dt, mpra_dt, genome, chrom,
                                      col_sig = col_region_sig)), size = 0.35)

  # 4. MPRA variant effects
  if (!is.null(mpra_dt))
    push(safe("MPRA Variants",
              build_mpra_variant_track(mpra_dt, chrom, genome, target_pos = pos,
                                       col_sig_up   = col_var_up,
                                       col_sig_down = col_var_down)), size = 0.35)

  # 4b. SCREEN cCREs (blue = brain-active, gray = other)
  if (!is.null(ccre_dt))
    push(safe("SCREEN cCREs", build_ccre_track(ccre_dt, genome, chrom)), size = 0.35)

  # 5. GTEx eQTL arcs — 2 tracks: brain (blue) and non-brain (gray), sig only (PIP > 0.1)
  if (!is.null(gtex_df) && nrow(gtex_df) > 0L) {
    gtex_df$is_sig <- gtex_df$pip > 0.1
    arc_tracks <- safe("GTEx arcs",
                       build_eqtl_arc_tracks(gtex_df, "GTEx eQTL", genome, chrom,
                                             arc_mode = "color_only", arc_lwd = arc_lwd))
    push(arc_tracks, size = 0.8)
  }

  # 6. Metabrain eQTL arcs — all brain tissue, so always blue (is_brain = TRUE), sig only
  if (!is.null(meta_df) && nrow(meta_df) > 0L) {
    meta_df_r          <- as.data.frame(meta_df)
    meta_df_r$is_brain <- TRUE
    arc_tracks <- safe("Metabrain arcs",
                       build_eqtl_arc_tracks(meta_df_r, "Metabrain\neQTL", genome, chrom,
                                             arc_mode = "color_only", arc_lwd = arc_lwd))
    push(arc_tracks, size = 0.8)
  }

  # 7. EMS signal (barplot by position)
  if (!is.null(ems_dt))
    push(safe("EMS", build_ems_track(ems_dt, genome, chrom)), size = 0.7)

  # 7b. EMS eQTL arcs (variant → gene TSS)
  if (!is.null(ems_arcs_df) && nrow(ems_arcs_df) > 0L) {
    arc_tracks <- safe("EMS arcs",
                       build_eqtl_arc_tracks(ems_arcs_df, "EMS\neQTL", genome, chrom,
                                             arc_mode = "color_only", arc_lwd = arc_lwd))
    push(arc_tracks, size = 0.8)
  }

  # 8. NGN2 ATAC — filled rectangles showing open chromatin regions
  if (show_ngn2_atac && !is.null(atac_dt))
    push(safe("ATAC", build_atac_track(atac_dt, genome, chrom)), size = 0.5)

  # 9. Brain ATAC-seq bigwig tracks (GSE113480 — astrocyte/cortical/hippocampus/motor)
  for (tr in brain_atac_trs)
    push(safe("Brain ATAC bw", tr), size = 0.5)

  # 10. UCSC / external bigwig ATAC tracks (brain cell types from track hubs)
  for (tr in ucsc_atac_trs)
    push(safe("UCSC ATAC", tr), size = 0.5)

  if (length(tracks) == 0L) {
    message("No tracks produced — check data paths and window size.")
    return(invisible(NULL))
  }

  # ── Wrap all tracks in HighlightTrack at variant position ────────────────────
  highlight_gr <- GRanges(chrom, IRanges(as.integer(pos) + 1L, as.integer(pos) + 1L))
  all_tracks <- HighlightTrack(
    trackList  = tracks,
    range      = highlight_gr,
    col        = COL_HIGHLIGHT,   # border color of the highlight band
    fill       = "#e31a1c18",     # very subtle red fill
    inBackground = TRUE
  )

  message(sprintf("  Track objects: %d | total height: %.1f in",
                  length(tracks), 2 + sum(track_sizes)))

  # ── Render ───────────────────────────────────────────────────────────────────
  pngfile      <- sub("\\.pdf$", ".png", outfile)
  total_height <- 2 + sum(track_sizes)

  do_plot <- function() {
    plotTracks(
      list(all_tracks),
      from             = from,
      to               = to,
      sizes            = track_sizes,
      background.title = "white",
      col.title        = "black",
      fontface.title   = 2,
      cex.title        = 0.8
    )
  }

  message("  Writing PDF → ", outfile)
  pdf(outfile, width = 10, height = total_height)
  tryCatch(do_plot(), error = function(e) { dev.off(); stop("plotTracks (PDF) failed: ", e$message) })
  dev.off()

  message("  Writing PNG → ", pngfile)
  png(pngfile, width = 1200, height = as.integer(total_height * 96), res = 96)
  tryCatch(do_plot(), error = function(e) { dev.off(); stop("plotTracks (PNG) failed: ", e$message) })
  dev.off()

  message("Done: ", outfile, " + ", pngfile)
  invisible(list(outfile = outfile, metabrain_genes = meta_genes_df))
}

