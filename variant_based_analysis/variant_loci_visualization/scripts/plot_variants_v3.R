build_mpra_region_track <- function(regions_dt, mpra_dt, genome, chrom,
                                    col_tested = COL_REGION_TESTED,
                                    col_sig    = COL_REGION_SIG) {
  regions_dt <- copy(regions_dt)
  s  <- as.integer(regions_dt$start)
  e  <- as.integer(regions_dt$end)
  ok <- !is.na(s) & !is.na(e)
  if (!all(ok)) {
    regions_dt <- regions_dt[ok]; s <- s[ok]; e <- e[ok]
  }
  if (nrow(regions_dt) == 0L) return(NULL)
  regions_dt[, is_sig_region := FALSE]
  if (!is.null(mpra_dt)) {
    sig_pos <- as.integer(mpra_dt[(ref_sig) | (alt_sig), pos0])
    if (length(sig_pos) > 0L) {
      region_gr <- GRanges(regions_dt$chr, IRanges(s, e))
      sig_gr    <- GRanges(chrom, IRanges(sig_pos, sig_pos + 1L))
      hits      <- findOverlaps(region_gr, sig_gr)
      regions_dt[queryHits(hits), is_sig_region := TRUE]
    }
  }
  fills <- ifelse(regions_dt$is_sig_region, col_sig, col_tested)
  gr    <- GRanges(regions_dt$chr, IRanges(s, e))
  AnnotationTrack(gr, genome = genome, name = "MPRA\nRegions",
                  fill = fills, col = NA, stacking = "dense",
                  background.title = "white", col.title = "black")
}

build_mpra_variant_track <- function(dt, chrom, genome, target_pos,
                                     col_tested    = COL_VAR_TESTED,
                                     col_sig_up    = COL_VAR_SIG_UP,
                                     col_sig_down  = COL_VAR_SIG_DOWN,
                                     col_highlight = COL_VAR_HIGHLIGHT) {
  fills   <- rep(col_tested, nrow(dt))
  borders <- rep(NA_character_, nrow(dt))
  fills[dt$is_sig & dt$logFC > 0]  <- col_sig_up
  fills[dt$is_sig & dt$logFC < 0]  <- col_sig_down
  target_idx <- which(dt$pos0 == target_pos)
  if (length(target_idx) > 0L) borders[target_idx] <- col_highlight
  p  <- as.integer(dt$pos0)
  gr <- GRanges(chrom, IRanges(p, p + 1L))
  AnnotationTrack(gr, genome = genome, name = "MPRA\nVariants",
                  fill = fills, col = borders, stacking = "dense",
                  background.title = "white", col.title = "black")
}

# ATAC: filled rectangles spanning full peak width, color-coded by signalValue.
build_atac_track <- function(dt, genome, chrom) {
  sv      <- dt$signalValue
  sv_norm <- (sv - min(sv)) / max(max(sv) - min(sv), 0.001)
  pal     <- colorRampPalette(c(COL_BRAIN_LIGHT, COL_BRAIN_DARK))(100L)
  fills   <- pal[pmax(1L, round(sv_norm * 99) + 1L)]

  # narrowPeak is 0-based: add 1 to start for GRanges (1-based)
  gr <- GRanges(dt$chr, IRanges(dt$start + 1L, dt$end))

  AnnotationTrack(
    gr, genome = genome, name = "NGN2\nATAC",
    fill = fills, col = NA,
    stacking = "dense",
    background.title = "white", col.title = "black"
  )
}

