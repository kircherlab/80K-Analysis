# Map abs(beta) in [0, 1+] to a color on a gradient.
# n_bins discrete levels for tractable track counts.
beta_to_color <- function(abs_beta, is_brain, is_sig, n_bins = 5L) {
  if (!is_sig) return(COL_GRAY)
  t    <- pmin(abs_beta / 1.0, 1.0)
  bin  <- max(1L, ceiling(t * n_bins))
  if (is_brain) {
    colorRampPalette(c(COL_BRAIN_LIGHT, COL_BRAIN_DARK))(n_bins)[bin]
  } else {
    colorRampPalette(c(COL_NONBR_LIGHT, COL_BLACK))(n_bins)[bin]
  }
}

# Map abs(beta) to color for negative arcs in color_only mode (warm palette).
beta_to_color_neg <- function(abs_beta, is_brain, is_sig, n_bins = 5L) {
  if (!is_sig) return(COL_GRAY)
  t    <- pmin(abs_beta / 1.0, 1.0)
  bin  <- max(1L, ceiling(t * n_bins))
  if (is_brain) {
    colorRampPalette(c("#F5C6A0", COL_BRAIN_NEG))(n_bins)[bin]
  } else {
    colorRampPalette(c("#CCAA88", "#8B4513"))(n_bins)[bin]
  }
}

# Map -log10(p) to a discrete lwd bin (3 levels). NA → thin line.
pval_to_lwd <- function(p_val) {
  p_val <- replace(p_val, is.na(p_val), 1)
  log_p <- -log10(pmax(p_val, 1e-300))
  ifelse(log_p > 3, 2.5, ifelse(log_p > 1.3, 1.5, 0.8))
}

# Map PIP (fine-mapping posterior) to lwd — used for GTEx which has no p-value.
pip_to_lwd <- function(pip) {
  pip <- replace(pip, is.na(pip), 0)
  ifelse(pip > 0.5, 2.5, ifelse(pip > 0.1, 1.5, 0.8))
}

