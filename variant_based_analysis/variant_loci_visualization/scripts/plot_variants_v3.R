load_mpra <- function(chrom, from, to) {
  chrom_num <- sub("^chr", "", chrom)
  tryCatch({
    dt <- fread(
      cmd       = sprintf("zcat '%s'", MPRA_FILE),
      select    = c(2L, 5L, 16L, 17L, 19L, 25L, 26L, 64L, 65L),
      col.names = c("chr_pos_ref_alt", "pos0", "padj", "logFC",
                    "is_sig", "ref_activity", "ref_sig", "alt_activity", "alt_sig")
    )
    dt <- dt[grepl(paste0("^", chrom_num, "-"), chr_pos_ref_alt)]
    dt <- dt[pos0 >= from & pos0 <= to]
    if (nrow(dt) == 0L) return(NULL)
    as_bool <- function(x) x == "True" | x == TRUE
    dt[, is_sig  := as_bool(is_sig)]
    dt[, ref_sig := as_bool(ref_sig)]
    dt[, alt_sig := as_bool(alt_sig)]
    dt[, chrom   := chrom]
    dt
  }, error = function(e) { message("MPRA load error: ", e$message); NULL })
}

