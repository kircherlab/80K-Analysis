#' Load a local bigwig over [from, to] and return a Gviz DataTrack.
build_brain_atac_bw_track <- function(bw_path, name, chrom, from, to,
                                       col = COL_BRAIN_DARK, genome = "hg38") {
  if (!file.exists(bw_path)) {
    message("[WARN] BigWig not found: ", bw_path); return(NULL)
  }
  tryCatch({
    gr <- GRanges(chrom, IRanges(from, to))
    bw <- rtracklayer::import.bw(bw_path, which = gr)
    if (length(bw) == 0L) return(NULL)
    DataTrack(
      range            = bw,
      data             = bw$score,
      type             = "histogram",
      genome           = genome,
      name             = name,
      col.histogram    = col,
      fill.histogram   = col,
      background.title = "white",
      col.title        = "black"
    )
  }, error = function(e) {
    message("[WARN] BigWig load failed (", name, "): ", e$message); NULL
  })
}

#' Build DataTracks for a subset of BRAIN_ATAC_BW entries.
