load_ems <- function(chrom, from, to) {
  files <- list.files(EMS_DIR, pattern = "\\.tsv\\.bgz$", full.names = TRUE)
  files <- files[!grepl("Zone.Identifier", files, fixed = TRUE)]

  load_one <- function(f) {
    tryCatch({
      cmd <- sprintf(
        "bgzip -d -c '%s' | awk -v chr='%s' -v f=%d -v t=%d 'NR==1{next} {split($1,a,\"_\"); if(a[1]==chr && int(a[2])>=f && int(a[2])<=t) print}'",
        f, chrom, from, to
      )
      dt <- fread(cmd = cmd,
                  col.names = c("v","g","rf_score_raw","ems","ems_normalized"))
      if (nrow(dt) == 0L) return(NULL)
      tissue       <- sub("\\.tsv\\.bgz$", "", sub("ems_top_", "", basename(f)))
      dt[, tissue   := tissue]
      dt[, is_brain := startsWith(tissue, "Brain_")]
      dt[, pos0     := as.integer(sub(paste0("^", chrom, "_([0-9]+)_.*"), "\\1", v))]
      dt
    }, error = function(e) NULL)
  }

  rows <- Filter(Negate(is.null), lapply(files, load_one))
  if (length(rows) == 0L) return(NULL)
  rbindlist(rows)
}

